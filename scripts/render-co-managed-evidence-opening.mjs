#!/usr/bin/env node
// Rewrite the opening of a co-managed evidence packet README from its ledgers.
//
// Every number and identity in the opening comes from a file or the running
// app, never from the author: guide counts from guide-coverage.json, requirement
// counts from completion-verdict.json, and the serving revision/build from the
// review dist's revision stamp and BUILD_ID, confirmed against the HTML the
// origin actually serves. The opening sits between two marker comments; the
// rest of the README is left as written and labelled historical.
//
// Usage: node scripts/render-co-managed-evidence-opening.mjs <packet-dir> --dist=<server dist dir> [--origin=URL] [--provenance=<runtime-provenance.json>] [--check]
import fs from 'node:fs';
import path from 'node:path';

const START = '<!-- ledger-opening:start (generated by scripts/render-co-managed-evidence-opening.mjs; do not edit by hand) -->';
const END = '<!-- ledger-opening:end -->';
const HISTORICAL = '> **Historical.** Everything below this line was written for earlier builds and is kept as a record. The opening above is the current state.';

const args = process.argv.slice(2);
const packet = args.find((arg) => !arg.startsWith('--'));
const option = (name) => args.find((arg) => arg.startsWith(`--${name}=`))?.slice(name.length + 3);
const dist = option('dist');
const origin = option('origin') ?? 'http://feature-co-managed-it.localhost:23374';
const provenancePath = option('provenance');
if (!packet || !dist) {
  console.error('usage: render-co-managed-evidence-opening.mjs <packet-dir> --dist=<server dist dir> [--origin=URL] [--provenance=<runtime-provenance.json>] [--check]');
  process.exit(2);
}

const repo = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(packet, file), 'utf8'));
const coverage = readJson('guide-coverage.json');
const verdict = readJson('completion-verdict.json');

const distDir = path.join(repo, 'server', dist);
const [servingRevision, servingFingerprint] = fs.readFileSync(path.join(distDir, '.alga-review-revision'), 'utf8').trim().split('+');
const servingBuild = fs.readFileSync(path.join(distDir, 'BUILD_ID'), 'utf8').trim();
const html = await (await fetch(`${origin}/auth/msp/signin`)).text();
if (!html.includes(servingBuild)) throw new Error(`${origin} does not serve ${servingBuild} from ${dist}`);
const health = (await fetch(`${origin}/api/health`)).status;
let provenanceLink = '';
if (provenancePath) {
  const provenance = JSON.parse(fs.readFileSync(provenancePath, 'utf8'));
  if (provenance.buildId !== servingBuild) throw new Error(`${provenancePath} records ${provenance.buildId}, but ${servingBuild} is serving`);
  provenanceLink = ` Runtime receipt: [${path.relative(packet, provenancePath)}](${path.relative(packet, provenancePath)}).`;
}

const short = (sha) => sha.slice(0, 10);
const guideName = (guide) => path.basename(guide.guide, '.html');
const byStatus = (status) => coverage.guides.filter((guide) => guide.coverageStatus === status);
const covered = byStatus('covered'), partial = byStatus('partial'), blocked = byStatus('blocked-external');
for (const [label, actual, expected] of [
  ['covered', covered.length, coverage.coveredGuides],
  ['partial', partial.length, coverage.partialGuides],
  ['blocked-external', blocked.length, coverage.blockedGuides],
]) {
  if (actual !== expected) throw new Error(`guide-coverage.json is inconsistent: ${actual} ${label} guides listed, summary says ${expected}`);
}
const recordedBuilds = [...new Set(covered.map((guide) => `${short(guide.build.sourceRevision)} / ${guide.build.buildId}`))];
const counts = Object.entries(verdict.counts).map(([state, count]) => `${count} ${state}`).join(', ');
const sameBuild = recordedBuilds.length === 1 && recordedBuilds[0] === `${short(servingRevision)} / ${servingBuild}`;

const opening = [
  START,
  `**Current state.** The ledger in [guide-coverage.json](guide-coverage.json) records **${covered.length} covered / ${partial.length} partial / ${blocked.length} blocked-external** of ${coverage.requiredGuides} guides.` +
    ` The blocked-external guides are ${blocked.map(guideName).join(', ')}. The covered guides were recorded on ${recordedBuilds.join(' and ')}.` +
    ` \`recordingReady=${coverage.recordingReady}\`, \`reviewReady=${coverage.reviewReady}\`.` +
    (coverage.currentEvidenceDirectory ? ` Current evidence: [${coverage.currentEvidenceDirectory}](${coverage.currentEvidenceDirectory}/README.md).` : ''),
  '',
  `**Serving now.** ${origin} serves application source \`${servingRevision}\` (diff fingerprint \`${servingFingerprint}\`), \`${servingBuild}\`, from \`server/${dist}\`. The sign-in HTML carries that build ID and \`/api/health\` returned ${health}.${provenanceLink}` +
    (sameBuild ? ' This is the build the guides were recorded on.' : ' The guides were not re-recorded on this build; their coverage stands for the build named above.'),
  '',
  `**Requirements.** [completion-verdict.json](completion-verdict.json) evaluates candidate \`${short(verdict.candidate)}\`: ${counts}; \`implementationReady=${verdict.implementationReady}\`, \`humanReviewReady=${verdict.humanReviewReady}\`, \`productionReady=${verdict.productionReady}\`. Guide coverage is not requirement acceptance. Rows are promoted at the review-packet step, not here.`,
  END,
  '',
  HISTORICAL,
].join('\n');

const readmePath = path.join(packet, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
let body;
if (readme.includes(START)) {
  body = readme.slice(readme.indexOf(END) + END.length).replace(/^\s*\n/, '').replace(`${HISTORICAL}\n`, '').replace(/^\s*\n/, '');
} else {
  // First generation: the paragraphs before the first heading were the old opening.
  const firstHeading = readme.search(/^# /m);
  body = firstHeading >= 0 ? readme.slice(firstHeading) : readme;
}
const next = `${opening}\n\n${body}`;
if (args.includes('--check')) {
  if (next !== readme) { console.error('README opening is stale'); process.exit(1); }
  console.log('README opening matches the ledgers');
} else {
  fs.writeFileSync(readmePath, next);
  console.log(opening);
}
