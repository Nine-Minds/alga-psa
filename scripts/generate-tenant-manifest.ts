#!/usr/bin/env npx tsx
/**
 * Tenant table manifest tooling.
 *
 *   npx tsx scripts/generate-tenant-manifest.ts --fks            regenerate packages/db/src/lib/tenantTableForeignKeys.ts
 *   npx tsx scripts/generate-tenant-manifest.ts --check          fail on drift, completeness gaps, violations or cycles
 *   npx tsx scripts/generate-tenant-manifest.ts --place <table>  print the legal insertion point for a new entry
 *
 * --fks and --check read a fully migrated database (CE + EE migrations):
 *   DB_HOST, DB_PORT, DB_USER, DB_PASSWORD, DB_NAME
 * --place reads only the committed snapshot and manifest (no database).
 *
 * The snapshot holds every foreign key whose child and parent both carry a
 * `tenant`/`tenant_id` column, so the ordering engine runs with no I/O.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import knex, { Knex } from 'knex';
import {
  TENANT_TABLE_MANIFEST,
  TenantManifestCycleError,
  computeTenantDeletionOrder,
  placeTenantTable,
  tenantDeletionOrder,
} from '../packages/db/src/lib/tenantTableManifest';
import { TENANT_TABLE_FOREIGN_KEYS, type TenantTableForeignKey } from '../packages/db/src/lib/tenantTableForeignKeys';
import { tenantTableMetadata } from '../packages/db/src/lib/tenantTableMetadata';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const SNAPSHOT_PATH = path.join(root, 'packages/db/src/lib/tenantTableForeignKeys.ts');
const ACTIVITY_PATH = path.join(root, 'ee/temporal-workflows/src/activities/tenant-deletion-activities.ts');

const RULES: Record<string, string> = { a: 'NO ACTION', r: 'RESTRICT', c: 'CASCADE', n: 'SET NULL', d: 'SET DEFAULT' };

function connect(): Knex {
  return knex({
    client: 'pg',
    connection: {
      host: process.env.DB_HOST || 'localhost',
      port: parseInt(process.env.DB_PORT || '5432', 10),
      user: process.env.DB_USER || 'postgres',
      password: process.env.DB_PASSWORD || '',
      database: process.env.DB_NAME || 'alga',
    },
  });
}

export async function readForeignKeys(db: Knex): Promise<TenantTableForeignKey[]> {
  // Composite FKs are (tenant, col); the snapshot records the non-tenant column(s).
  const result = await db.raw(`
    WITH tenant_tables AS (
      SELECT c.table_name
      FROM information_schema.columns c
      JOIN information_schema.tables t
        ON t.table_name = c.table_name AND t.table_schema = c.table_schema
      WHERE c.table_schema = 'public'
        AND c.column_name IN ('tenant', 'tenant_id')
        AND t.table_type = 'BASE TABLE'
    )
    SELECT con.conname AS name, child.relname AS child, parent.relname AS parent, con.confdeltype AS rule,
      (SELECT string_agg(a.attname, ',' ORDER BY k.ord)
         FROM unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord)
         JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
        WHERE a.attname NOT IN ('tenant', 'tenant_id')) AS columns
    FROM pg_constraint con
    JOIN pg_class child ON child.oid = con.conrelid
    JOIN pg_class parent ON parent.oid = con.confrelid
    JOIN pg_namespace ns ON ns.oid = child.relnamespace
    WHERE con.contype = 'f' AND con.conparentid = 0 AND ns.nspname = 'public'
      AND child.relname IN (SELECT table_name FROM tenant_tables)
      AND parent.relname IN (SELECT table_name FROM tenant_tables)
    ORDER BY child.relname, parent.relname, con.conname
  `);
  return result.rows.map((row: any) => ({
    child: row.child,
    parent: row.parent,
    column: row.columns ?? '',
    deleteRule: RULES[row.rule] ?? row.rule,
    name: row.name,
  }));
}

function renderSnapshot(foreignKeys: TenantTableForeignKey[]): string {
  const rows = foreignKeys.map(fk =>
    `  { child: '${fk.child}', parent: '${fk.parent}', column: '${fk.column}', deleteRule: '${fk.deleteRule}', name: '${fk.name}' },`);
  return `/**
 * GENERATED by scripts/generate-tenant-manifest.ts --fks. Do not edit by hand.
 *
 * Foreign keys between tenant-keyed tables, read from a fully migrated database
 * (CE + EE migrations). The ordering engine in tenantTableManifest.ts reads this
 * constant, so it never touches the database. Regenerate after any migration that
 * adds or changes a foreign key; \`--check\` fails on drift.
 */

export interface TenantTableForeignKey {
  child: string;
  parent: string;
  /** Referencing column(s) on the child, tenant column excluded. */
  column: string;
  deleteRule: string;
  /** Constraint name, for diagnostics. */
  name: string;
}

export const TENANT_TABLE_FOREIGN_KEYS: readonly TenantTableForeignKey[] = [
${rows.join('\n')}
];
`;
}

function parseActivityLiteral(): string[] {
  const content = fs.readFileSync(ACTIVITY_PATH, 'utf-8');
  const match = content.match(/const\s+TENANT_TABLES_DELETION_ORDER\s*:\s*string\[\]\s*=\s*\[([\s\S]*?)\n\];/)
    ?? content.match(/export\s+const\s+TENANT_TABLES_DELETION_ORDER\s*:\s*string\[\]\s*=\s*\[([\s\S]*?)\n\];/);
  if (!match) throw new Error('Could not find TENANT_TABLES_DELETION_ORDER in the activity source');
  return [...match[1].replace(/\/\/.*$/gm, '').matchAll(/'([a-z_0-9]+)'/g)].map(m => m[1]);
}

const keyOf = (fk: TenantTableForeignKey) => `${fk.name}|${fk.child}|${fk.parent}|${fk.column}|${fk.deleteRule}`;

async function check(): Promise<number> {
  const problems: string[] = [];

  // 1. Order legality and cycles (no database needed).
  try {
    const computed = computeTenantDeletionOrder();
    for (const v of computed.violations) {
      problems.push(`violation: ${v.child} (#${v.childIndex}) must be deleted before ${v.parent} (#${v.parentIndex}) [${v.column}, ${v.deleteRule}]`);
    }
    const declared = [...tenantDeletionOrder()];
    if (!computed.violations.length && computed.order.some((t, i) => t !== declared[i])) {
      problems.push('computed order differs from declared order without violations');
    }
  } catch (error) {
    if (error instanceof TenantManifestCycleError) problems.push(`cycle: ${error.cycle.join(' -> ')}`);
    else throw error;
  }

  // 2. The activity literal is a golden projection of the manifest.
  const literal = parseActivityLiteral();
  const ordered = [...tenantDeletionOrder()];
  if (literal.length !== ordered.length || literal.some((t, i) => t !== ordered[i])) {
    problems.push(`activity TENANT_TABLES_DELETION_ORDER (${literal.length}) differs from the manifest order (${ordered.length})`);
  }

  // 3. Every ordered entry resolves a scope.
  for (const entry of TENANT_TABLE_MANIFEST) {
    if (!tenantTableMetadata[entry.table] && !entry.scope && entry.deletion !== 'excluded') {
      problems.push(`scope: ${entry.table} has no tenantTableMetadata entry and declares no scope`);
    }
    if (entry.deletion === 'excluded' && !entry.reason) problems.push(`exclusion: ${entry.table} has no reason`);
  }

  // 4. Database: snapshot drift and completeness.
  const db = connect();
  try {
    const live = await readForeignKeys(db);
    const have = new Set(TENANT_TABLE_FOREIGN_KEYS.map(keyOf));
    const want = new Set(live.map(keyOf));
    for (const k of want) if (!have.has(k)) problems.push(`drift: foreign key missing from snapshot: ${k}`);
    for (const k of have) if (!want.has(k)) problems.push(`drift: snapshot foreign key not in database: ${k}`);

    const tables = await db.raw(`
      SELECT DISTINCT c.table_name FROM information_schema.columns c
      JOIN information_schema.tables t ON t.table_name = c.table_name AND t.table_schema = c.table_schema
      WHERE c.table_schema = 'public' AND c.column_name IN ('tenant','tenant_id')
        AND c.table_name NOT LIKE 'pg\\_%' AND c.table_name NOT LIKE 'citus\\_%' AND t.table_type = 'BASE TABLE'`);
    const known = new Set(TENANT_TABLE_MANIFEST.map(entry => entry.table));
    for (const row of tables.rows as Array<{ table_name: string }>) {
      if (!known.has(row.table_name)) problems.push(`completeness: ${row.table_name} has a tenant column and no manifest entry`);
    }
  } finally {
    await db.destroy();
  }

  if (problems.length) {
    console.error(`tenant manifest check FAILED (${problems.length}):`);
    for (const p of problems) console.error(`  - ${p}`);
    return 1;
  }
  console.log(`tenant manifest check OK: ${ordered.length} ordered tables, ${TENANT_TABLE_FOREIGN_KEYS.length} foreign keys, no drift`);
  return 0;
}

function place(table: string): number {
  const order = [...tenantDeletionOrder()];
  let computed: string[] = order;
  try {
    computed = computeTenantDeletionOrder().order;
  } catch (error) {
    if (!(error instanceof TenantManifestCycleError)) throw error;
    console.error(`warning: ${error.message}; placing against the declared order`);
  }
  const w = placeTenantTable(table, computed);
  console.log(JSON.stringify(w, null, 2));
  if (w.earliestIndex > w.latestIndex) {
    console.error(`No legal position: ${w.mustFollow.join(', ')} must precede ${table}, which must precede ${w.mustPrecede.join(', ')}.`);
    return 1;
  }
  console.log(w.insertAfter
    ? `Insert { table: '${table}', deletion: 'ordered' } immediately after '${w.insertAfter}' (any index in ${w.earliestIndex}..${w.latestIndex}).`
    : `Insert { table: '${table}', deletion: 'ordered' } at the start of the manifest (any index in ${w.earliestIndex}..${w.latestIndex}).`);
  return 0;
}

async function main(): Promise<number> {
  const args = process.argv.slice(2);
  if (args.includes('--fks')) {
    const db = connect();
    try {
      const fks = await readForeignKeys(db);
      fs.writeFileSync(SNAPSHOT_PATH, renderSnapshot(fks));
      console.log(`wrote ${fks.length} foreign keys to ${path.relative(root, SNAPSHOT_PATH)}`);
      return 0;
    } finally {
      await db.destroy();
    }
  }
  if (args.includes('--check')) return check();
  const i = args.indexOf('--place');
  if (i >= 0 && args[i + 1]) return place(args[i + 1]);
  console.error('usage: generate-tenant-manifest.ts --fks | --check | --place <table>');
  return 2;
}

main().then(code => process.exit(code), error => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
