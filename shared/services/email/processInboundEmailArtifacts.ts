function isUniqueViolation(error: any): boolean {
  return error?.code === '23505' || String(error?.message || '').toLowerCase().includes('duplicate');
}

function isBase64(value: string): boolean {
  return /^[A-Za-z0-9+/=\s]+$/.test(value);
}

function normalizeContentId(value: string | undefined | null): string {
  if (!value) return '';
  return String(value).trim().replace(/^cid:/i, '').replace(/^<|>$/g, '').toLowerCase();
}

interface InboundAttachmentTrailOutcome {
  attachmentId: string;
  fileName: string;
  contentType: string;
  fileSize: number | null;
  status: 'skipped' | 'failed';
  reason: string;
}

/**
 * Skip reasons that describe attachments which were not actually dropped.
 * Inline/CID parts are served from the comment body, and `non_image_embedded`
 * rows are synthetic records generated by body extraction. Reporting them
 * would make every HTML email with an inline image noisy.
 */
const ATTACHMENT_TRAIL_EXCLUDED_SKIP_REASONS = new Set(['inline', 'non_image_embedded']);

function formatAttachmentSize(bytes: number | null): string {
  if (bytes === null || !Number.isFinite(bytes) || bytes < 0) return 'unknown size';
  if (bytes < 1024) return `${bytes} B`;
  const units = ['KB', 'MB', 'GB', 'TB'];
  let value = bytes / 1024;
  let unitIndex = 0;
  while (value >= 1024 && unitIndex < units.length - 1) {
    value /= 1024;
    unitIndex += 1;
  }
  return `${value.toFixed(1)} ${units[unitIndex]}`;
}

function buildAttachmentTrailOutcome(
  attachment: { id?: unknown; name?: unknown; contentType?: unknown; size?: unknown },
  persistResult: Record<string, any> | null | undefined
): InboundAttachmentTrailOutcome | null {
  if (!persistResult) return null;

  const isSkipped = persistResult.success === true && persistResult.skipped === true;
  const isFailed = persistResult.success === false;
  if (!isSkipped && !isFailed) return null;

  const reasonSlug = String(persistResult.reason ?? '');
  if (isSkipped && ATTACHMENT_TRAIL_EXCLUDED_SKIP_REASONS.has(reasonSlug)) return null;

  const fileSize =
    typeof attachment?.size === 'number' && Number.isFinite(attachment.size) ? attachment.size : null;

  return {
    attachmentId: String(attachment?.id ?? ''),
    fileName: String(attachment?.name ?? '') || '(unnamed attachment)',
    contentType: String(attachment?.contentType ?? '') || 'application/octet-stream',
    fileSize,
    status: isSkipped ? 'skipped' : 'failed',
    reason: String(persistResult.message ?? '') || reasonSlug || 'attachment not processed',
  };
}

/**
 * The original-email `.eml` is persisted on its own (system-artifact) path, so
 * it needs its own trail outcome. Its failures/skips must surface on the ticket
 * exactly like a user attachment's do.
 */
function buildOriginalEmailTrailOutcome(
  emailId: string,
  persistResult: Record<string, any> | null | undefined
): InboundAttachmentTrailOutcome | null {
  if (!persistResult) return null;

  const isSkipped = persistResult.success === true && persistResult.skipped === true;
  const isFailed = persistResult.success === false;
  if (!isSkipped && !isFailed) return null;

  return {
    attachmentId: ORIGINAL_EMAIL_ATTACHMENT_ID,
    fileName: String(persistResult.fileName ?? '') || buildOriginalEmailFileName(emailId),
    contentType: String(persistResult.contentType ?? '') || 'message/rfc822',
    fileSize: typeof persistResult.fileSize === 'number' ? persistResult.fileSize : null,
    status: isSkipped ? 'skipped' : 'failed',
    reason:
      String(persistResult.message ?? '') ||
      String(persistResult.reason ?? '') ||
      'original email not archived',
  };
}

function buildAttachmentTrailBlocks(outcomes: InboundAttachmentTrailOutcome[]): unknown[] {
  return outcomes.map((outcome) => ({
    type: 'paragraph',
    content: [
      {
        type: 'text',
        text: `Attachment "${outcome.fileName}" (${outcome.contentType}, ${formatAttachmentSize(outcome.fileSize)}) was not attached: ${outcome.reason}.`,
        styles: {},
      },
    ],
  }));
}

function parseTrailFilesFromMetadata(metadata: unknown): InboundAttachmentTrailOutcome[] {
  if (!metadata) return [];
  let parsed: any = metadata;
  if (typeof metadata === 'string') {
    try {
      parsed = JSON.parse(metadata);
    } catch {
      return [];
    }
  }
  const files = parsed?.inboundAttachmentTrail?.files;
  if (!Array.isArray(files)) return [];
  return files.filter((file: any) => file && typeof file === 'object');
}

/**
 * Resolve the shared storage size ceiling so inbound uses the same limit as
 * manual upload. Returns null when storage config is unavailable (the
 * validator still enforces the ceiling itself; this only drives the cheap
 * pre-download early-out).
 *
 * Loads the narrow `config/storage` subpath, never the package barrel: the
 * built email-service worker (native Node, `tsc` + `tsc-alias`) cannot resolve
 * the barrel's transitive `@alga-psa/validation` source exports.
 */
async function resolveInboundMaxAttachmentBytes(): Promise<number | null> {
  try {
    const { getStorageConfig } = await import('@alga-psa/storage/config/storage');
    const config = await getStorageConfig();
    const provider = config?.providers?.[config.defaultProvider];
    return typeof provider?.maxFileSize === 'number' ? provider.maxFileSize : null;
  } catch (error) {
    console.warn('processInboundEmailInApp: failed to resolve storage size ceiling (continuing)', {
      error: error instanceof Error ? error.message : String(error),
    });
    return null;
  }
}

/**
 * The only rejections the shared storage policy raises for a user upload
 * (`packages/storage/src/config/storage.ts`). Matching these exact errors keeps
 * a genuine policy rejection distinct from an infrastructure failure (a failed
 * module load, config error, or DB error), which must never be relabeled as
 * "too large" or "type not allowed".
 */
const STORAGE_SIZE_LIMIT_PATTERN = /^File size exceeds limit of \d+ bytes$/;
const STORAGE_TYPE_NOT_ALLOWED_MESSAGE = 'File type not allowed';

type StoragePolicyCheck =
  | { status: 'allowed' }
  | { status: 'rejected'; kind: 'size' | 'type' }
  | { status: 'infrastructure_error'; message: string };

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function classifyStoragePolicyError(error: unknown): StoragePolicyCheck {
  const message = errorMessage(error);
  if (STORAGE_SIZE_LIMIT_PATTERN.test(message)) {
    return { status: 'rejected', kind: 'size' };
  }
  if (message === STORAGE_TYPE_NOT_ALLOWED_MESSAGE) {
    return { status: 'rejected', kind: 'type' };
  }
  return { status: 'infrastructure_error', message };
}

/**
 * Validate a real inbound attachment against the same policy manual upload
 * uses. Loads the narrow `config/storage` subpath so the built worker can run
 * it, and returns a classified outcome instead of collapsing every thrown
 * error into a policy rejection.
 */
// LEVERAGE: friction inbound-revalidates-storage-policy — inbound email
// re-derives the storage MIME/size gate that StorageService.validateFileUpload
// already owns for manual uploads; both should route through the shared policy.
async function validateInboundAttachmentUpload(input: {
  mimeType: string;
  fileSize: number;
}): Promise<StoragePolicyCheck> {
  let validateFileUpload: (mimeType: string, fileSize: number) => Promise<void>;
  try {
    ({ validateFileUpload } = await import('@alga-psa/storage/config/storage'));
  } catch (error) {
    return { status: 'infrastructure_error', message: errorMessage(error) };
  }

  try {
    await validateFileUpload(input.mimeType, input.fileSize);
    return { status: 'allowed' };
  } catch (error) {
    return classifyStoragePolicyError(error);
  }
}

/**
 * Validate a product-generated artifact (the original `.eml`, synthetic
 * embedded images) against the shared size ceiling only — the tenant
 * attachment allow-list never applies. Same runtime-safe subpath as the
 * user-upload validator.
 */
async function validateInboundSystemArtifact(fileSize: number): Promise<StoragePolicyCheck> {
  let validateSystemArtifact: (fileSize: number) => Promise<void>;
  try {
    ({ validateSystemArtifact } = await import('@alga-psa/storage/config/storage'));
  } catch (error) {
    return { status: 'infrastructure_error', message: errorMessage(error) };
  }

  try {
    await validateSystemArtifact(fileSize);
    return { status: 'allowed' };
  } catch (error) {
    return classifyStoragePolicyError(error);
  }
}

function isStorageInfrastructureError(
  check: StoragePolicyCheck
): check is { status: 'infrastructure_error'; message: string } {
  return check.status === 'infrastructure_error';
}

function isStoragePolicyRejection(
  check: StoragePolicyCheck
): check is { status: 'rejected'; kind: 'size' | 'type' } {
  return check.status === 'rejected';
}

/**
 * Post one internal system comment per email summarizing attachments that were
 * skipped or failed. Idempotent: keyed off a metadata marker on the comment and
 * merged under an advisory lock so durable artifact-worker re-runs (and
 * concurrent per-artifact jobs) never post a duplicate.
 */
async function postInboundAttachmentTrailComment(input: {
  tenantId: string;
  providerId: string;
  ticketId: string;
  emailId: string;
  outcomes: InboundAttachmentTrailOutcome[];
}): Promise<void> {
  if (input.outcomes.length === 0) return;
  try {
    const { TicketModel } = await import('../../models/ticketModel');
    await withTenantAdminTransaction(input.tenantId, async (trx: any, db: any) => {
      // Serialize concurrent artifact-worker jobs for the same email so they
      // merge into a single trail comment instead of racing to insert two.
      await trx.raw('select pg_advisory_xact_lock(hashtext(?))', [
        `inbound-attachment-trail:${input.tenantId}:${input.emailId}`,
      ]);

      const existing = await db.table('comments')
        .where('ticket_id', input.ticketId)
        .whereRaw("metadata->'inboundAttachmentTrail'->>'emailId' = ?", [input.emailId])
        .first('comment_id', 'metadata');

      const mergedById = new Map<string, InboundAttachmentTrailOutcome>();
      for (const file of parseTrailFilesFromMetadata(existing?.metadata)) {
        mergedById.set(String(file.attachmentId || file.fileName), file);
      }
      let added = false;
      for (const outcome of input.outcomes) {
        const key = String(outcome.attachmentId || outcome.fileName);
        if (mergedById.has(key)) continue;
        mergedById.set(key, outcome);
        added = true;
      }
      const mergedFiles = Array.from(mergedById.values());

      if (existing?.comment_id && !added) {
        return;
      }

      const metadata = {
        inboundAttachmentTrail: {
          emailId: input.emailId,
          providerId: input.providerId,
          files: mergedFiles,
        },
      };

      if (existing?.comment_id) {
        await db.table('comments')
          .where({ comment_id: existing.comment_id })
          .update({
            note: JSON.stringify(buildAttachmentTrailBlocks(mergedFiles)),
            metadata: JSON.stringify(metadata),
            updated_at: new Date(),
          });
        return;
      }

      await TicketModel.createComment(
        {
          ticket_id: input.ticketId,
          content: JSON.stringify(buildAttachmentTrailBlocks(mergedFiles)),
          is_internal: true,
          is_resolution: false,
          is_system_generated: true,
          author_type: 'system',
          metadata,
        },
        input.tenantId,
        trx
      );
    });
  } catch (error) {
    console.warn('processInboundEmailInApp: failed to post inbound attachment trail comment (continuing)', {
      tenantId: input.tenantId,
      ticketId: input.ticketId,
      emailId: input.emailId,
      error: error instanceof Error ? error.message : String(error),
    });
  }
}

function resolveAttachmentConcurrency(
  explicitLimit?: number
): number {
  if (Number.isFinite(explicitLimit) && (explicitLimit as number) > 0) {
    return Math.max(1, Math.min(8, Math.floor(explicitLimit as number)));
  }

  const raw =
    process.env.IMAP_INBOUND_EMAIL_IN_APP_ARTIFACT_CONCURRENCY ||
    process.env.INBOUND_EMAIL_IN_APP_ARTIFACT_CONCURRENCY;
  if (!raw) return 1;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || parsed <= 0) return 1;
  return Math.max(1, Math.min(8, Math.floor(parsed)));
}

async function runWithConcurrency<T>(
  items: T[],
  limit: number,
  worker: (item: T) => Promise<void>
): Promise<void> {
  if (items.length === 0) return;
  const concurrency = Math.max(1, Math.min(limit, items.length));
  let index = 0;

  const runners = Array.from({ length: concurrency }, async () => {
    while (true) {
      const current = index;
      index += 1;
      if (current >= items.length) {
        break;
      }
      await worker(items[current]);
    }
  });

  await Promise.all(runners);
}

