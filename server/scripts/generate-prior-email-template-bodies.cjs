#!/usr/bin/env node
/**
 * Generates the catalogue of prior system email template bodies the derived-provenance backfill
 * matches old tenant rows against:
 *
 *   packages/email/src/priorSystemBodies.generated.ts
 *
 * A tenant row written before provenance existed carries a body some past system template had.
 * The template modules can still render those bodies (quoteEmail/quoteReminder take
 * `{ reviewLink: false }` for the bodies before 2026-11-13), so the catalogue is rendered from the
 * modules, never copied by hand; a test regenerates it and fails on any difference.
 *
 * Add a source below when a system template change must stay recognisable for rows that predate
 * it. Rows stamped from now on never need the catalogue.
 *
 *   node server/scripts/generate-prior-email-template-bodies.cjs          # rewrite the file
 *   node server/scripts/generate-prior-email-template-bodies.cjs --check  # exit 1 if it is stale
 */

const fs = require('node:fs');
const path = require('node:path');

const templates = path.resolve(__dirname, '../migrations/utils/templates/email/quotes');
const OUTPUT = path.resolve(__dirname, '../../packages/email/src/priorSystemBodies.generated.ts');

/** Each source: the module, the options that reproduce the older body, and what changed after it. */
const SOURCES = [
  {
    label: 'before the quoteReviewLink call to action (2026-11-13)',
    module: require(path.join(templates, 'quoteEmail.cjs')),
    options: { reviewLink: false },
  },
  {
    label: 'before the quoteReviewLink call to action (2026-11-13)',
    module: require(path.join(templates, 'quoteReminder.cjs')),
    options: { reviewLink: false },
  },
];

function buildCatalogue() {
  const catalogue = {};
  for (const { label, module: source, options } of SOURCES) {
    const { templateName, translations } = source.getTemplate(options);
    for (const translation of translations) {
      const byLanguage = (catalogue[templateName] ??= {});
      (byLanguage[translation.language] ??= []).push({
        label,
        subject: translation.subject,
        html_content: translation.htmlContent,
        text_content: translation.textContent,
      });
    }
  }
  return catalogue;
}

function render(catalogue) {
  return `/* eslint-disable */
// GENERATED by server/scripts/generate-prior-email-template-bodies.cjs — do not edit by hand.
// Bodies of system email templates as they were before a later change, rendered from the template
// modules, for the derived-provenance backfill to recognise untouched branded copies of them.

export interface PriorSystemBody {
  label: string;
  subject: string;
  html_content: string;
  text_content: string;
}

/** template name -> language -> prior bodies, newest first. */
export const PRIOR_SYSTEM_BODIES: Record<string, Record<string, PriorSystemBody[]>> =
${JSON.stringify(catalogue, null, 2)};
`;
}

module.exports = { buildCatalogue, render, OUTPUT };

if (require.main === module) {
  const content = render(buildCatalogue());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== content) {
      console.error(`${path.relative(process.cwd(), OUTPUT)} is stale; run this script without --check.`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, content);
    console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
  }
}
