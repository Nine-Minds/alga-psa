/**
 * Asset group members (FR-E9)
 * Path: /api/v1/asset-groups/[id]/members
 */

import { ApiAssetGroupController } from '@/lib/api/controllers/ApiAssetGroupController';
import { handleApiError } from '@/lib/api/middleware/apiMiddleware';
import { withApiKeyRouteAuth } from '@/lib/api/middleware/withApiKeyRouteAuth';

const controller = new ApiAssetGroupController();

export const POST = withApiKeyRouteAuth<{ id: string }>(async (request, { params }) => {
  try {
    const resolvedParams = await params;
    const req = request as any;
    req.params = resolvedParams;
    return await controller.addMembers(req, resolvedParams);
  } catch (error) {
    return handleApiError(error);
  }
});

export const DELETE = withApiKeyRouteAuth<{ id: string }>(async (request, { params }) => {
  try {
    const resolvedParams = await params;
    const req = request as any;
    req.params = resolvedParams;
    return await controller.removeMember(req, resolvedParams);
  } catch (error) {
    return handleApiError(error);
  }
});

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';
